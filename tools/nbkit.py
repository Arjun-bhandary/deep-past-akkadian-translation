"""Helpers for generating self-contained Kaggle notebooks from the ``deep_past`` package.

Kaggle code-competition notebooks run without internet, so a notebook cannot ``pip install``
this repository.  Instead every generated notebook embeds the package modules it needs as
``%%writefile`` cells (the transitive closure of the CLI modules it calls, found by parsing
imports — including the lazy ones inside functions) and puts them on ``sys.path`` /
``PYTHONPATH``.  ``src/`` stays the single source of truth: edit the package, then re-run
``python tools/build_notebooks.py`` (``--check`` verifies the committed notebooks are fresh).
"""
from __future__ import annotations

import ast
import json
from pathlib import Path
from typing import Dict, Iterable, List, Sequence, Set

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src"
PKG = "deep_past"
KAGGLE_SRC = "/kaggle/working/deep_past_src"


def md(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": _lines(text.strip("\n"))}


def code(text: str) -> dict:
    return {"cell_type": "code", "execution_count": None, "metadata": {}, "outputs": [],
            "source": _lines(text.strip("\n"))}


def _lines(text: str) -> List[str]:
    parts = text.split("\n")
    return [p + "\n" for p in parts[:-1]] + [parts[-1]]


# ----------------------------------------------------------------------------- imports
def _module_path(module: str) -> Path:
    rel = Path(*module.split("."))
    as_pkg = SRC / rel / "__init__.py"
    return as_pkg if as_pkg.exists() else SRC / rel.with_suffix(".py")


def _imports_of(module: str) -> Set[str]:
    """Package-internal modules imported anywhere in ``module`` (top-level or lazy)."""
    path = _module_path(module)
    tree = ast.parse(path.read_text(encoding="utf-8"))
    is_pkg = path.name == "__init__.py"
    package = module if is_pkg else module.rpartition(".")[0]
    found: Set[str] = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name == PKG or alias.name.startswith(PKG + "."):
                    found.add(alias.name)
        elif isinstance(node, ast.ImportFrom):
            if node.level:
                base_parts = package.split(".")
                if node.level > 1:
                    base_parts = base_parts[: -(node.level - 1)]
                base = ".".join(base_parts)
                target = f"{base}.{node.module}" if node.module else base
            else:
                target = node.module or ""
            if not (target == PKG or target.startswith(PKG + ".")):
                continue
            found.add(target)
            for alias in node.names:  # "from deep_past import metric" imports a submodule
                candidate = f"{target}.{alias.name}"
                if _module_path(candidate).exists():
                    found.add(candidate)
    return {m for m in found if _module_path(m).exists()}


def module_closure(entry_modules: Iterable[str]) -> List[str]:
    """Entry modules + everything they (transitively) import from the package + parent packages."""
    todo = list(entry_modules)
    seen: Set[str] = set()
    while todo:
        mod = todo.pop()
        if mod in seen:
            continue
        if not _module_path(mod).exists():
            raise FileNotFoundError(f"module {mod} not found under {SRC}")
        seen.add(mod)
        parts = mod.split(".")
        for i in range(1, len(parts)):  # parent packages' __init__.py
            parent = ".".join(parts[:i])
            if parent not in seen:
                todo.append(parent)
        todo.extend(_imports_of(mod) - seen)
    return sorted(seen)


def module_files(modules: Sequence[str]) -> List[Path]:
    return sorted({_module_path(m) for m in modules})


# ----------------------------------------------------------------------------- cells
def embed_package_cells(entry_modules: Iterable[str], extra_files: Sequence[str] = ()) -> List[dict]:
    """Cells that write the needed package files (+ extra repo files such as configs) to /kaggle/working."""
    files = module_files(module_closure(entry_modules))
    dirs = sorted({str(Path(KAGGLE_SRC) / f.relative_to(SRC).parent) for f in files} |
                  {str(Path(KAGGLE_SRC).parent / "deep_past_repo" / Path(e).parent) for e in extra_files})
    cells = [
        md("### Embedded `deep_past` package\n"
           "The cells below write the package modules this notebook needs (generated by "
           "`tools/build_notebooks.py` from `src/deep_past`, so the notebook runs offline)."),
        code("import os\nfor d in " + json.dumps(dirs, indent=1) + ":\n    os.makedirs(d, exist_ok=True)"),
    ]
    for f in files:
        rel = f.relative_to(SRC).as_posix()
        cells.append(code(f"%%writefile {KAGGLE_SRC}/{rel}\n" + f.read_text(encoding="utf-8").rstrip("\n")))
    for e in extra_files:
        content = (ROOT / e).read_text(encoding="utf-8").rstrip("\n")
        cells.append(code(f"%%writefile {Path(KAGGLE_SRC).parent}/deep_past_repo/{e}\n" + content))
    cells.append(code(
        "import os, sys\n"
        f"SRC = {KAGGLE_SRC!r}\n"
        "if SRC not in sys.path:\n"
        "    sys.path.insert(0, SRC)\n"
        "# subprocesses (python -m deep_past....) need the path too\n"
        "os.environ['PYTHONPATH'] = SRC + os.pathsep + os.environ.get('PYTHONPATH', '')\n"
        "import deep_past\n"
        "print('deep_past', deep_past.__version__, 'from', deep_past.__file__)"
    ))
    return cells


def notebook(cells: List[dict]) -> dict:
    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "pygments_lexer": "ipython3"},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


def dumps(nb: dict) -> str:
    # stable cell ids keep diffs clean between regenerations
    for i, cell in enumerate(nb["cells"]):
        cell["id"] = f"cell-{i:03d}"
    return json.dumps(nb, indent=1, ensure_ascii=False) + "\n"


def write_notebooks(notebooks: Dict[str, dict], out_dir: Path, check: bool = False) -> List[str]:
    """Write (or with ``check`` compare) notebooks; returns names that are stale/changed."""
    out_dir.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, nb in notebooks.items():
        path = out_dir / name
        text = dumps(nb)
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            changed.append(name)
            if not check:
                path.write_text(text, encoding="utf-8")
    return changed
